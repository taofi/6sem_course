-- create_pdb.sql

CREATE PLUGGABLE DATABASE COURSEPDB
  ADMIN USER adminPDB IDENTIFIED BY oracle
  ROLES = (dba)
  DEFAULT TABLESPACE opdbtblsp
    DATAFILE '/opt/oracle/oradata/XE/COURSEPDB/COURSEPDB.dbf' SIZE 250M AUTOEXTEND ON
  FILE_NAME_CONVERT = (
    '/opt/oracle/oradata/XE/pdbseed/',
    '/opt/oracle/oradata/XE/COURSEPDB/'
  )
  STORAGE (MAXSIZE 2G)
  PATH_PREFIX = '/opt/oracle/oradata/XE/COURSEPDB/';

ALTER PLUGGABLE DATABASE COURSEPDB OPEN;
ALTER PLUGGABLE DATABASE COURSEPDB SAVE STATE;

ALTER SESSION SET CONTAINER=COURSEPDB;
GRANT CONNECT, RESOURCE, DBA TO adminPDB;

